import { promises as fs } from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.resolve(scriptDir, '..');
const quizDir = path.join(webRoot, 'src/content/quizzes/en');
const accessMapPath = path.join(webRoot, 'src/data/quiz-access-map.json');
const outputPath = path.join(webRoot, 'api/_quiz-runtime.generated.js');
const contentRoot = path.join(webRoot, 'src/content');

async function walk(directory) {
  const entries = await fs.readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const fullPath = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await walk(fullPath));
    else files.push(fullPath);
  }
  return files;
}

function normalizeRoute(value) {
  if (value === '/') return value;
  return value.replace(/\/+$/, '');
}

const accessMap = JSON.parse(await fs.readFile(accessMapPath, 'utf8'));
const contentFiles = (await walk(contentRoot)).filter(
  (file) => /\.mdx?$/.test(file) && !file.includes(`${path.sep}quizzes${path.sep}`),
);
const contentSlugs = new Set();
for (const file of contentFiles) {
  const text = await fs.readFile(file, 'utf8');
  const match = text.match(/^slug:\s*["']?([^\n"']+)["']?\s*$/m);
  if (match) contentSlugs.add(normalizeRoute(match[1].trim()));
}
const quizFiles = (await fs.readdir(quizDir)).filter((name) => name.endsWith('.json')).sort();
const quizzes = await Promise.all(
  quizFiles.map(async (name) => JSON.parse(await fs.readFile(path.join(quizDir, name), 'utf8'))),
);

const accessById = new Map(accessMap.quizzes.map((item) => [item.canonicalId, item]));
const runtime = {};

for (const quiz of quizzes.sort((a, b) => a.canonicalId.localeCompare(b.canonicalId))) {
  const access = accessById.get(quiz.canonicalId);
  if (!access) {
    throw new Error(`Missing access-map entry for ${quiz.canonicalId}`);
  }

  runtime[quiz.canonicalId] = {
    title: quiz.title,
    questionCount: quiz.questionCount,
    passScore: accessMap.passScore,
    released: access.released,
    relatedLessonUrl: access.relatedLessonUrl,
    unlocksChapter: access.unlocksChapter,
    unlocksChapterAvailable: access.unlocksChapter ? contentSlugs.has(normalizeRoute(access.unlocksChapter)) : false,
    nextQuizUrl: access.nextQuizUrl,
    completionUrl: access.completionUrl,
    questions: quiz.questions.map((question) => ({
      number: question.number,
      correctAnswer: question.correctAnswer,
      allowedAnswerKeys: question.options.map((option) => option.key),
      explanation: question.explanation,
    })),
  };
}

const output = `// Generated by scripts/generate-quiz-runtime.mjs. Do not edit manually.\n` +
  `export const QUIZ_RUNTIME_VERSION = ${JSON.stringify(accessMap.version)};\n` +
  `export const QUIZ_RUNTIME = ${JSON.stringify(runtime, null, 2)};\n`;

if (process.argv.includes('--check')) {
  let existing = '';
  try {
    existing = await fs.readFile(outputPath, 'utf8');
  } catch {
    // Report the same actionable error for a missing or stale file.
  }

  if (existing !== output) {
    console.error('Quiz runtime is missing or stale. Run: npm run generate:quizzes');
    process.exit(1);
  }

  console.log(`Quiz runtime is current (${quizFiles.length} quizzes).`);
  process.exit(0);
}

await fs.writeFile(outputPath, output, 'utf8');
console.log(`Generated ${path.relative(webRoot, outputPath)} from ${quizFiles.length} quizzes.`);
