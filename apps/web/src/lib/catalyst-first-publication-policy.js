const legacyBySlug = new Map(LEGACY_CATALYST_PUBLICATION_PINS.map((x) => [x.slug, x]));
const policyIntroductionUtcDate = '2026-11-13';

export function isPinnedLegacyCatalyst(brief) {
  const pin = legacyBySlug.get(brief?.slug);
  return Boolean(pin
    && pin.eventKey === brief.eventKey
    && pin.eventDate === brief.eventDate
    && pin.phase === brief.phase
    && pin.generatedAt === brief.generatedAt);
}

function validUtcCalendarDate(date) {
  if (typeof date !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(date)) return false;
  const parsed = new Date(date + 'T00:00:00.000Z');
  return !Number.isNaN(parsed.getTime()) && parsed.toISOString().slice(0,10) === date;
}

// Returns a user-readable *error* or null. No file writes, clock simulation,
// network calls, external market claims or Date.now-dependent auto-publication.
export function catalystFirstPublicationIssue(brief, { todayUtc = new Date().toISOString().slice(0,10) } = {}) {
  const isLegacy = isPinnedLegacyCatalyst(brief);
  const first = brief?.firstPublishedDate;

  if (brief?.status !== 'published') {
    return first == null ? null : 'A Catalyst review/draft cannot claim a first public availability date.';
  }
  if (first == null || first === '') {
    return isLegacy
      ? null
      : 'A newly published Catalyst requires a separately reviewed firstPublishedDate (YYYY-MM-DD UTC).';
  }
  if (!validUtcCalendarDate(first)) {
    return 'firstPublishedDate must be an actual calendar day in YYYY-MM-DD UTC form.';
  }
  if (!validUtcCalendarDate(todayUtc)) {
    return 'Publication validation requires an actual UTC calendar date.';
  }
  if (first > todayUtc) {
    return 'firstPublishedDate cannot claim future public availability.';
  }
  if (!isLegacy) {
    if (first < policyIntroductionUtcDate) {
      return 'New Catalyst publication dates cannot predate adoption of this provenance guard.';
    }
    const draftedAt = new Date(brief.generatedAt);
    if (Number.isNaN(draftedAt.getTime())) {
      return 'New Catalyst generatedAt must be a valid preparation timestamp.';
    }
    if (first < draftedAt.toISOString().slice(0,10)) {
      return 'The first public date cannot precede the content preparation date.';
    }
  }
  return null;
}

export function catalystArticleDatePublished(brief, options = {}) {
  if (brief?.status !== 'published') {
    throw new Error('A non-published Catalyst has no public Article datePublished.');
  }
  const issue = catalystFirstPublicationIssue(brief, options);
  if (issue) throw new Error(issue);
  // Legacy values are unchanged for source-compatibility only; historical
  // generatedAt is not asserted to be independently verified first-publication.
  return brief.firstPublishedDate || brief.generatedAt;
}
